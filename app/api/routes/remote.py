def _constants_path() -> Path:
    # Constants file where the token will be written
    return Path(__file__).resolve().parents[2] / "core" / "constants.py"


def _write_token_to_constants(token: str, raw: dict[str, Any] | None = None) -> None:
    p = _constants_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    # Minimal constants file with a single token constant. Also stores raw JSON for debugging.
    content_lines = [
        "# Auto-generated by /api/token endpoint. Do not edit manually.",
        f"REMOTE_TOKEN = {token!r}",
    ]
    if raw is not None:
        # Best-effort raw data for later inspection (not required to be imported elsewhere)
        content_lines.append(f"REMOTE_TOKEN_RAW = {raw!r}")
    p.write_text("\n".join(content_lines) + "\n", encoding="utf-8")


async def _fetch_token() -> dict:
    async with httpx.AsyncClient(timeout=15.0) as client:
        resp = await client.post(AUTH_URL, headers=AUTH_HEADERS, data=AUTH_FORM)
        resp.raise_for_status()
        return resp.json()


def _extract_token(data: dict[str, Any]) -> str | None:
    # Try a few common keys
    for key in ("access_token", "token", "id_token"):
        val = data.get(key)
        print('>>>>val', val);
        if isinstance(val, str) and val:
            return val
    return None


async def _refresh_token_and_reload() -> str | None:
    """刷新 token 并重新加载模块以更新全局 REMOTE_TOKEN"""
    global REMOTE_TOKEN
    try:
        data = await _fetch_token()
        token = _extract_token(data)
        if not token:
            print('>>>>refresh_token: Token not found in auth response')
            return None
        _write_token_to_constants(token, raw=data)
        # 重新加载 core.constants 模块以更新 REMOTE_TOKEN
        if 'core.constants' in sys.modules:
            importlib.reload(sys.modules['core.constants'])
            from core.constants import REMOTE_TOKEN as NEW_TOKEN
            REMOTE_TOKEN = NEW_TOKEN
        else:
            from core.constants import REMOTE_TOKEN as NEW_TOKEN
            REMOTE_TOKEN = NEW_TOKEN
        print('>>>>refresh_token: Token refreshed successfully')
        return token
    except Exception as e:
        print(f'>>>>refresh_token failed: {repr(e)}')
        return None


async def _make_request_with_retry(request_func):
    """执行 HTTP 请求，如果遇到 401 错误则自动刷新 token 并重试一次"""
    try:
        return await request_func()
    except httpx.HTTPStatusError as e:
        if e.response.status_code == 401:
            print('>>>>401 Unauthorized detected, refreshing token...')
            new_token = await _refresh_token_and_reload()
            if new_token:
                print('>>>>Token refreshed, retrying request...')
                # 重试一次
                return await request_func()
            else:
                print('>>>>Failed to refresh token, raising original error')
                raise
        else:
            raise


