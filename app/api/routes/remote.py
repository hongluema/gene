async def _download_binary_stream(pk: int | str):
    """下载二进制数据流（PDF）并流式返回"""
    try:
        async with httpx.AsyncClient(timeout=None, follow_redirects=True) as client:
            headers = {
                "accept": "application/pdf,application/octet-stream,*/*",
                "Authorization": f"Bearer {REMOTE_TOKEN}",
            }
            url = f"{BASE_API}/api/pdf/download/wx?pk={pk}"
            async with client.stream("POST", url, headers=headers) as resp:
                resp.raise_for_status()
                # 流式读取二进制数据
                async for chunk in resp.aiter_bytes():
                    yield chunk
    except httpx.HTTPStatusError as e:
        if e.response.status_code == 401:
            print('>>>>401 Unauthorized detected in stream, refreshing token...')
            new_token = await _refresh_token_and_reload()
            if new_token:
                print('>>>>Token refreshed, retrying stream request...')
                # 重试一次
                async with httpx.AsyncClient(timeout=None, follow_redirects=True) as client:
                    headers = {
                        "accept": "application/pdf,application/octet-stream,*/*",
                        "Authorization": f"Bearer {REMOTE_TOKEN}",
                    }
                    url = f"{BASE_API}/api/pdf/download?pk={pk}"
                    async with client.stream("POST", url, headers=headers) as resp:
                        resp.raise_for_status()
                        # 流式读取二进制数据
                        async for chunk in resp.aiter_bytes():
                            yield chunk
            else:
                print('>>>>Failed to refresh token, raising original error')
                raise
        else:
            raise

def _serialize_datetime(obj: Any) -> Any:
    """递归地将字典中的 datetime 和 date 对象转换为字符串"""
    if isinstance(obj, datetime):
        return obj.isoformat()
    elif isinstance(obj, date):
        return obj.isoformat()
    elif isinstance(obj, dict):
        return {key: _serialize_datetime(value) for key, value in obj.items()}
    elif isinstance(obj, list):
        return [_serialize_datetime(item) for item in obj]
    else:
        return obj


def _get_projects_data(db: Session):
    """获取项目数据的核心逻辑，可被其他模块调用"""
    sql = text("select * from program where usable = 1")
    result = db.execute(sql)
    # 使用 mappings() 将 Row 对象转换为字典，然后转换为普通字典列表以便 JSON 序列化
    rows = result.mappings().all()
    # 将 RowMapping 对象转换为普通字典，并将 id 字段转换为字符串
    projects = []
    for row in rows:
        project_dict = dict(row)
        if 'id' in project_dict and project_dict['id'] is not None:
            project_dict['id'] = str(project_dict['id'])
        projects.append(project_dict)
    # 递归处理 datetime 对象
    return _serialize_datetime(projects)


